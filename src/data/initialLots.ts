function derivePeneira(lote: string): string {
  const upper = lote.toUpperCase();
  if (upper.startsWith('1MG') || upper.startsWith('1GO') || upper.startsWith('1DF')) {
    return '5,75 mm';
  }
  if (upper.startsWith('2MG') || upper.startsWith('2GO') || upper.startsWith('2DF')) {
    return '6,75 mm';
  }
  return '5,75 mm';
}

function parsePercent(val?: string): number | string | undefined {
  if (!val || val.trim() === '') return undefined;
  const clean = val.replace('%', '').trim().replace(',', '.');
  const num = parseFloat(clean);
  return isNaN(num) ? val.trim() : num;
}

export function parseRawLotsText(rawText: string): LoteItem[] {
  const lines = rawText.split('\n');
  const items: LoteItem[] = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Header row skip
    if (i === 0 && (line.toLowerCase().includes('lote') || line.toLowerCase().includes('germin'))) {
      continue;
    }

    // Split line by tab, pipe, or multiple spaces
    let parts: string[] = [];
    if (line.includes('\t')) {
      parts = line.split('\t').map(p => p.trim());
    } else if (line.includes('|')) {
      parts = line.split('|').map(p => p.trim());
    } else if (line.includes(';')) {
      parts = line.split(';').map(p => p.trim());
    } else {
      parts = line.split(/\s{2,}/).map(p => p.trim());
    }

    if (parts.length >= 4) {
      // Format 1: 6 columns [Lote, Germinação, Vigor, Cultivar, Cat, Peso]
      if (parts.length >= 6) {
        const lote = parts[0];
        const germinacao = parsePercent(parts[1]);
        const vigor = parsePercent(parts[2]);
        const cultivar = parts[3];
        const categoria = parts[4];
        const rawPeso = parts[5].replace(/[^\d.,]/g, '').replace(',', '.');
        const peso = parseFloat(rawPeso) || 0;

        if (lote) {
          items.push({
            lote,
            peneira: derivePeneira(lote),
            categoria: categoria || 'S1',
            peso,
            cultura: 'Soja',
            cultivar: cultivar || 'Soja',
            variedade: cultivar || 'Soja',
            germinacao,
            vigor,
            safra: '2024/2025',
            conferido: false,
          });
        }
      } else {
        // Format 2: 4 columns [Lote, Peneira, Categoria, Peso]
        const lote = parts[0];
        const peneira = parts[1] || derivePeneira(lote);
        const categoria = parts[2] || 'S1';
        const rawPeso = parts[3].replace(/[^\d.,]/g, '').replace(',', '.');
        const peso = parseFloat(rawPeso) || 0;

        if (lote) {
          items.push({
            lote,
            peneira,
            categoria,
            peso,
            cultura: 'Soja',
            cultivar: 'Soja',
            safra: '2024/2025',
            conferido: false,
          });
        }
      }
    }
  }

  return items;
}

