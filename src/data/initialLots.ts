export function parseRawLotsText(rawText: string): LoteItem[] {
  const lines = rawText.split('\n');
  const items: LoteItem[] = [];

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    // Supports format: Lote | Peneira | Categoria | Peso or tab or semicolon
    let parts: string[] = [];
    if (trimmed.includes('|')) {
      parts = trimmed.split('|').map(p => p.trim());
    } else if (trimmed.includes(';')) {
      parts = trimmed.split(';').map(p => p.trim());
    } else if (trimmed.includes('\t')) {
      parts = trimmed.split('\t').map(p => p.trim());
    } else if (trimmed.includes(',')) {
      parts = trimmed.split(',').map(p => p.trim());
    } else {
      parts = trimmed.split(/\s{2,}/).map(p => p.trim());
    }

    if (parts.length >= 4) {
      const lote = parts[0];
      const peneira = parts[1];
      const categoria = parts[2];
      // Clean peso (remove 'kg', replace commas with dot if decimal, or parseInt)
      const rawPeso = parts[3].replace(/[^\d.,]/g, '').replace(',', '.');
      const peso = parseFloat(rawPeso) || 0;

      if (lote) {
        items.push({
          lote,
          peneira,
          categoria,
          peso,
          conferido: false,
        });
      }
    }
  }

  return items;
}

